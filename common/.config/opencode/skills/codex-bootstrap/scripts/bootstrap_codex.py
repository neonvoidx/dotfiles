def backup_existing_file(path: Path) -> Path | None:
    if not path.exists():
        return None
    timestamp = datetime.now().strftime("%Y%m%d%H%M%S")
    backup_path = path.with_name(f"{path.name}.bak.{timestamp}")
    shutil.copy2(path, backup_path)
    return backup_path


def backup_existing_path(path: Path) -> Path | None:
    if not path.exists() and not path.is_symlink():
        return None
    timestamp = datetime.now().strftime("%Y%m%d%H%M%S")
    backup_path = path.with_name(f"{path.name}.bak.{timestamp}")
    if path.is_symlink() or path.is_file():
        shutil.copy2(path, backup_path, follow_symlinks=False)
    elif path.is_dir():
        shutil.copytree(path, backup_path, symlinks=True)
    return backup_path


def replace_existing_path(path: Path) -> Path | None:
    if not path.exists() and not path.is_symlink():
        return None
    backup_path = backup_existing_path(path)
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)
    return backup_path


def replace_existing_skill_path(path: Path, backups_dir: Path) -> Path | None:
    if not path.exists() and not path.is_symlink():
        return None
    backups_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d%H%M%S")
    backup_path = backups_dir / f"{path.name}.bak.{timestamp}"
    if path.is_symlink() or path.is_file():
        shutil.copy2(path, backup_path, follow_symlinks=False)
        path.unlink()
    elif path.is_dir():
        shutil.copytree(path, backup_path, symlinks=True)
        shutil.rmtree(path)
    return backup_path


def render_agents_content(source: Path, repo_root: Path) -> str:
    rendered = source.read_text(encoding="utf-8")
    for relative_path in AGENTS_RELATIVE_PATHS:
        absolute_path = format_path(repo_root / relative_path)
        rendered = rendered.replace(f"`{relative_path}`", f"`{absolute_path}`")
        rendered = rendered.replace(f"({relative_path})", f"({absolute_path})")
        rendered = rendered.replace(f": `{relative_path}`", f": `{absolute_path}`")
        rendered = rendered.replace(f"- `{relative_path}`", f"- `{absolute_path}`")
    return rendered


