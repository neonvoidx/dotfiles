def split_blocks(text: str) -> list[str]:
    blocks: list[str] = []
    current: list[str] = []
    for line in text.splitlines(keepends=True):
        stripped = line.strip()
        is_header = stripped.startswith("[") and stripped.endswith("]")
        if is_header and current:
            blocks.append("".join(current))
            current = [line]
        else:
            current.append(line)
    if current:
        blocks.append("".join(current))
    return blocks


def block_header(block: str) -> str | None:
    for line in block.splitlines():
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            return stripped
    return None


def filter_blocks(text: str, enabled_skills: set[str], enabled_mcp: set[str]) -> str:
    kept: list[str] = []
    for block in split_blocks(text):
        header = block_header(block)
        if header is None:
            kept.append(block)
            continue

        if header == "[[skills.config]]":
            match = SKILL_NAME_RE.search(block)
            if match and match.group(1) not in enabled_skills:
                continue
            kept.append(block)
            continue

        match = MCP_SECTION_RE.match(header)
        if match and match.group(1) in AVAILABLE_MCP_SERVERS and match.group(1) not in enabled_mcp:
            continue

        kept.append(block)
    return "".join(kept)


def replace_setting(text: str, key: str, value: str | None) -> str:
    pattern = re.compile(rf"(?m)^#?\s*{re.escape(key)}\s*=.*$")
    if not value:
        return text
    replacement = f'{key} = "{value}"'
    if pattern.search(text):
        return pattern.sub(replacement, text, count=1)
    return f"{replacement}\n{text}"


def replace_optional_root(text: str, placeholder: str, value: str | None) -> str:
    line_with_comma = f'  "{placeholder}",\n'
    line_without_comma = f'  "{placeholder}"\n'
    if value:
        return text.replace(placeholder, value)
    return text.replace(line_with_comma, "").replace(line_without_comma, "")


def replace_mcp_env_file_arg(text: str, server_name: str, env_file: str) -> str:
    header = f"[mcp_servers.{server_name}]"
    start = text.find(header)
    if start == -1:
        return text
    end = text.find("\n[", start + len(header))
    if end == -1:
        end = len(text)
    section = text[start:end]
    lines = section.splitlines(keepends=True)
    for index, line in enumerate(lines[:-1]):
        if line.strip() != '"--env-file",':
            continue
        newline = "\n" if lines[index + 1].endswith("\n") else ""
        indent = lines[index + 1][: len(lines[index + 1]) - len(lines[index + 1].lstrip())]
        lines[index + 1] = f'{indent}"{shell_quote(env_file)}",{newline}'
        return text[:start] + "".join(lines) + text[end:]
    return text


