def write_generated_agent_files(repo_root: Path, codex_home: Path) -> list[tuple[str, Path, Path | None]]:
    agents_dir = codex_home / "agents"
    agents_dir.mkdir(parents=True, exist_ok=True)

    agent_definitions = [
        parse_agent_markdown(source)
        for source in sorted((repo_root / "agents").glob("*.md"))
        if source.is_file()
    ]
    written: list[tuple[str, Path, Path | None]] = []
    expected_paths: set[Path] = set()
    for agent_definition in agent_definitions:
        destination = agents_dir / f'{agent_definition["name"]}.toml'
        expected_paths.add(destination)
        backup_path = write_helper_file(destination, render_agent_config(agent_definition))
        written.append((agent_definition["name"], destination, backup_path))

    for existing in sorted(agents_dir.glob("*.toml")):
        if existing in expected_paths or not is_generated_agent_file(existing):
            continue
        existing.unlink()

    return written


def install_skill_links(
    repo_root: Path,
    codex_home: Path,
    enabled_skills: set[str],
) -> list[tuple[str, Path, str]]:
    skills_dir = codex_home / "skills"
    skill_backups_dir = codex_home / "skill-backups"
    skills_dir.mkdir(parents=True, exist_ok=True)

    results: list[tuple[str, Path, str]] = []
    for skill_name in sorted(enabled_skills):
        source = repo_root / "skills" / skill_name
        destination = skills_dir / skill_name
        if not (source / "SKILL.md").exists():
            results.append((skill_name, destination, f"missing source: {source}"))
            continue
        if destination.is_symlink():
            current_target = destination.resolve()
            if current_target == source.resolve():
                results.append((skill_name, destination, "already linked"))
                continue
            backup_path = replace_existing_skill_path(destination, skill_backups_dir)
            destination.symlink_to(source, target_is_directory=True)
            results.append((skill_name, destination, f"relinked; backup at {backup_path}"))
            continue
        if destination.exists():
            backup_path = replace_existing_skill_path(destination, skill_backups_dir)
            destination.symlink_to(source, target_is_directory=True)
            results.append((skill_name, destination, f"linked; backup at {backup_path}"))
            continue
        destination.symlink_to(source, target_is_directory=True)
        results.append((skill_name, destination, "linked"))
    return results


def write_helper_file(path: Path, content: str, *, executable: bool = False) -> Path | None:
    path.parent.mkdir(parents=True, exist_ok=True)
    backup_path = backup_existing_file(path)
    path.write_text(content, encoding="utf-8")
    if executable:
        path.chmod(0o755)
    return backup_path


